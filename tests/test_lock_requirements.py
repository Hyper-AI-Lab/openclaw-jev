"""ops/lock_requirements.py, the hashed lock of requirements.in and requirements-dev.in.

Offline: the script's two seams are fakes. Its pip call resolves over a small fake index (a requirement's own pin,
else its constraint, else the newest version) and writes pip's report; its PyPI fetch answers from the same index. The
repo is tmp_path.
"""
import hashlib
import importlib.util
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
RUNTIME_IN = "fastapi==0.135.1\n"
DEV_IN = "-r requirements.in\npytest==9.0.3\n"
# Production's pip freeze, as the first lock reads it: metadata names, and outlines, which no requirement reaches.
FREEZE = ("fastapi==0.135.1\noutlines==1.2.12\npluggy==1.6.0\npydantic==2.12.5\npydantic_core==2.41.5\n"
          "iniconfig==2.3.0\npytest==9.0.3\nstarlette==0.52.1\n")
RUNTIME = {"fastapi": "0.135.1", "pydantic": "2.12.5", "pydantic-core": "2.41.5", "starlette": "0.52.1"}
DEV = {"iniconfig": "2.3.0", "pluggy": "1.6.0", "pytest": "9.0.3"}
# The fake index: each name's dependencies and its newest release.
DEPS = {"fastapi": ["starlette", "pydantic"], "pydantic": ["pydantic-core"], "pytest": ["iniconfig", "pluggy"],
        "alembic": ["sqlalchemy", "mako"]}
NEWEST = {"fastapi": "0.136.0", "starlette": "1.10.0", "pydantic": "2.13.0", "pydantic-core": "2.42.0",
          "pytest": "9.1.0", "iniconfig": "2.4.0", "pluggy": "1.7.0", "alembic": "1.16.5", "sqlalchemy": "2.0.50",
          "mako": "1.3.10"}
# pip writes a distribution's metadata name, which is not always the canonical one.
METADATA_NAMES = {"pydantic-core": "pydantic_core"}
# pip 24.0's report of a constraint it cannot keep (pip/_internal/resolution/resolvelib/factory.py).
CONFLICT = """\
Collecting fastapi==0.136.0 (from -r requirements.in (line 1))
  Using cached fastapi-0.136.0-py3-none-any.whl.metadata (28 kB)
INFO: pip is looking at multiple versions of fastapi to determine which version is compatible with other requirements. This could take a while.
ERROR: Cannot install -r requirements.in (line 1) because these package versions have conflicting dependencies.

The conflict is caused by:
    fastapi 0.136.0 depends on starlette<1.11 and >=0.53.0
    The user requested (constraint) starlette==0.52.1

To fix this you could try to:
1. loosen the range of package versions you've specified
2. remove package versions to allow pip attempt to solve the dependency conflict

ERROR: ResolutionImpossible: for help visit https://pip.pypa.io/en/latest/topics/dependency-resolution/#dealing-with-dependency-conflicts
"""


def load():
    module_spec = importlib.util.spec_from_file_location("lock_requirements", ROOT / "ops" / "lock_requirements.py")
    module = importlib.util.module_from_spec(module_spec)
    module_spec.loader.exec_module(module)
    return module


def wheel_sha(name: str, version: str) -> str:
    return hashlib.sha256(f"{name}-{version}.whl".encode()).hexdigest()


def sdist_sha(name: str, version: str) -> str:
    return hashlib.sha256(f"{name}-{version}.tar.gz".encode()).hexdigest()


def plain_pins(text: str) -> dict:
    """A constraint file the script wrote: nothing but ``name==version`` lines."""
    return dict(line.split("==") for line in text.splitlines())


def entry(name: str, version: str) -> str:
    """A pin as the lock writes it: every file's hash of the release, sorted."""
    hashes = sorted([wheel_sha(name, version), sdist_sha(name, version)])
    return f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{sha}" for sha in hashes) + "\n"


def lock_files(runtime: dict, dev: dict) -> tuple:
    """requirements.txt and requirements-dev.txt as the script writes them for these pins."""
    header = "# generated by ops/lock_requirements.py from {}; edit the .in file and run make lock\n"
    runtime_pins = "".join(entry(name, version) for name, version in sorted(runtime.items()))
    dev_pins = "".join(entry(name, version) for name, version in sorted(dev.items()))
    return (header.format("requirements.in") + runtime_pins,
            header.format("requirements-dev.in") + "-r requirements.txt\n" + dev_pins)


class FakePip:
    """``pip install --dry-run --report`` over the fake index: each requirement's own pin, else its constraint
    (unless ``ignore_constraints``), else its newest release; a pin that contradicts a constraint is pip's conflict.
    Each call is recorded with its .in file and its constraint files as they were at the call."""

    def __init__(self, repo: Path, *, ignore_constraints: bool = False):
        self.repo, self.ignore_constraints, self.calls = repo, ignore_constraints, []

    def requested(self, source: Path) -> dict:
        pinned = {}
        for line in source.read_text().splitlines():
            if line.startswith("-r "):
                pinned.update(self.requested(source.parent / line[3:]))
            elif "==" in line:
                name, version = line.split("==")
                pinned[name] = version
        return pinned

    def __call__(self, args):
        source = args[args.index("-r") + 1]
        held = [plain_pins(Path(args[i + 1]).read_text()) for i, arg in enumerate(args) if arg == "-c"]
        self.calls.append({"args": args, "source": source, "constraints": held})
        constrained = {} if self.ignore_constraints else {name: v for pins in held for name, v in pins.items()}
        pinned = self.requested(self.repo / source)
        for name, version in pinned.items():
            if constrained.get(name, version) != version:
                return 1, CONFLICT
        chosen, todo = {}, list(pinned)
        while todo:
            name = todo.pop(0)
            if name not in chosen:
                chosen[name] = pinned.get(name) or constrained.get(name) or NEWEST[name]
                todo += DEPS.get(name, [])
        install = [{"metadata": {"name": METADATA_NAMES.get(name, name), "version": version},
                    "download_info": {"url": f"https://files.example/{name}-{version}.whl",
                                      "archive_info": {"hash": f"sha256={wheel_sha(name, version)}",
                                                       "hashes": {"sha256": wheel_sha(name, version)}}}}
                   for name, version in chosen.items()]
        Path(args[args.index("--report") + 1]).write_text(json.dumps({"version": "1", "install": install}))
        return 0, "Would install " + " ".join(f"{name}-{version}" for name, version in chosen.items()) + "\n"


@pytest.fixture
def script(tmp_path, monkeypatch):
    """The script on a tmp_path repo holding the two .in files, with the fake pip and a fake PyPI that lists a wheel
    and an sdist for every release (``script.missing`` names the releases whose wheel it does not list)."""
    module = load()
    (tmp_path / "requirements.in").write_text(RUNTIME_IN)
    (tmp_path / "requirements-dev.in").write_text(DEV_IN)
    (tmp_path / "freeze.txt").write_text(FREEZE)
    pip = FakePip(tmp_path)
    fetched, missing = [], set()

    def fetch_json(url):
        fetched.append(url)
        name, version = url.split("/")[4:6]
        files = [sdist_sha(name, version)] + ([] if (name, version) in missing else [wheel_sha(name, version)])
        return {"info": {"name": name, "version": version}, "urls": [{"digests": {"sha256": sha}} for sha in files]}

    monkeypatch.setattr(module, "REPO", tmp_path)
    monkeypatch.setattr(module, "run_pip", pip)
    monkeypatch.setattr(module, "fetch_json", fetch_json)
    module.pip, module.fetched, module.missing, module.repo = pip, fetched, missing, tmp_path
    return module


def first_lock(script) -> None:
    """The first lock, against production's freeze; the fake pip's calls are cleared after it."""
    assert script.main(["--constraint", str(script.repo / "freeze.txt")]) == 0
    script.pip.calls.clear()


def written(repo: Path) -> tuple:
    return ((repo / "requirements.txt").read_text(), (repo / "requirements-dev.txt").read_text())


def test_the_script_writes_the_expected_files(script, capsys):
    assert script.main(["--constraint", str(script.repo / "freeze.txt")]) == 0

    assert written(script.repo) == lock_files(RUNTIME, DEV)
    # Each resolution is pip's own, installing nothing, under production's pins in canonical form; the dev one also
    # under the runtime set.
    production = {"fastapi": "0.135.1", "outlines": "1.2.12", "pluggy": "1.6.0", "pydantic": "2.12.5",
                  "pydantic-core": "2.41.5", "iniconfig": "2.3.0", "pytest": "9.0.3", "starlette": "0.52.1"}
    assert [(call["source"], call["constraints"]) for call in script.pip.calls] == [
        ("requirements.in", [production]), ("requirements-dev.in", [production, RUNTIME])]
    for call in script.pip.calls:
        assert call["args"][:4] == ["install", "--dry-run", "--ignore-installed", "--disable-pip-version-check"]
        assert "--report" in call["args"] and "--quiet" not in call["args"] and "-q" not in call["args"]
    assert sorted(script.fetched) == sorted(f"https://pypi.org/pypi/{name}/{version}/json"
                                            for name, version in {**RUNTIME, **DEV}.items())
    out = capsys.readouterr().out
    assert "moved pins: none (7 of the 8 constraints are in the lock, each at its version)" in out
    assert out.splitlines()[-1] == "outside the lock: outlines"


def test_adding_a_package_moves_no_existing_pin(script, capsys):
    first_lock(script)
    committed = {**RUNTIME, **DEV}
    (script.repo / "requirements.in").write_text(RUNTIME_IN + "alembic==1.16.5\n")

    assert script.main([]) == 0

    # Without --constraint the committed lock is the constraint set: every pin of both files, at its version.
    assert script.pip.calls[0]["constraints"] == [committed]
    assert script.pip.calls[1]["constraints"][0] == committed
    # The old pins stay where they were (the index has newer releases of each); alembic comes with its dependencies,
    # at their newest.
    added = {"alembic": "1.16.5", "mako": "1.3.10", "sqlalchemy": "2.0.50"}
    assert written(script.repo) == lock_files({**RUNTIME, **added}, DEV)
    assert capsys.readouterr().out.splitlines()[-1] == "outside the lock: none"


def test_a_changed_in_pin_leaves_the_constraints(script):
    first_lock(script)
    (script.repo / "requirements.in").write_text("fastapi==0.136.0\n")

    assert script.main([]) == 0

    others = {name: version for name, version in {**RUNTIME, **DEV}.items() if name != "fastapi"}
    assert script.pip.calls[0]["constraints"] == [others]
    assert written(script.repo) == lock_files({**RUNTIME, "fastapi": "0.136.0"}, DEV)


def test_a_forced_move_exits_1_and_names_the_pin(script, monkeypatch, capsys):
    first_lock(script)
    before = written(script.repo)
    capsys.readouterr()
    monkeypatch.setattr(script, "run_pip", lambda args: (1, CONFLICT))

    assert script.main([]) == 1

    out = capsys.readouterr().out
    assert out.startswith("would move: starlette==0.52.1\nchange that pin in requirements.in (or requirements-dev.in) "
                          "to move it\n")
    assert "The conflict is caused by:" in out and "outside the lock" not in out
    assert written(script.repo) == before


def test_a_failure_that_names_no_constraint_prints_pips_lines(script, monkeypatch, capsys):
    monkeypatch.setattr(script, "run_pip", lambda args: (1, "ERROR: No matching distribution found for fastapi\n"))

    assert script.main(["--constraint", str(script.repo / "freeze.txt")]) == 1

    assert capsys.readouterr().out == "ERROR: No matching distribution found for fastapi\n"
    assert not (script.repo / "requirements.txt").exists() and not (script.repo / "requirements-dev.txt").exists()


def test_a_report_that_moves_a_constrained_pin_exits_1(script, monkeypatch, capsys):
    first_lock(script)
    before = written(script.repo)
    capsys.readouterr()
    pip = FakePip(script.repo, ignore_constraints=True)
    monkeypatch.setattr(script, "run_pip", pip)

    assert script.main([]) == 1

    assert capsys.readouterr().out == ("would move: pydantic==2.12.5, pydantic-core==2.41.5, starlette==0.52.1\n"
                                       "change that pin in requirements.in (or requirements-dev.in) to move it\n")
    assert written(script.repo) == before


def test_a_hash_missing_from_pypi_exits_1(script, capsys):
    script.missing.add(("starlette", "0.52.1"))

    assert script.main(["--constraint", str(script.repo / "freeze.txt")]) == 1

    assert capsys.readouterr().out == ("PyPI lists no file of starlette==0.52.1 with the sha256 pip chose "
                                       f"({wheel_sha('starlette', '0.52.1')})\n")
    assert not (script.repo / "requirements.txt").exists() and not (script.repo / "requirements-dev.txt").exists()
