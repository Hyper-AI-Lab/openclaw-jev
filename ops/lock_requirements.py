#!/usr/bin/env python3
"""Lock RMP's dependencies: requirements.txt, the runtime closure of requirements.in, and requirements-dev.txt, the
test tools of requirements-dev.in on top of it. Every pin carries the sha256 of each file of its release, so
``pip install --require-hashes -r requirements-dev.txt`` installs exactly this set on the host and on CI's runner.

    make lock                                                   # after an edit of a .in file; needs the network
    <venv>/bin/python ops/lock_requirements.py --constraint FILE

pip's own resolver does the work (``pip install --dry-run --ignore-installed --report``, which installs nothing), and
every resolution is constrained. By default the constraints are the committed lock's pins, less each name whose line
in requirements.in or requirements-dev.in names another version: a new package resolves around the existing pins, and
a pin moves only through its .in line. ``--constraint FILE`` takes FILE's ``name==version`` lines instead: the first
lock, against production's ``pip freeze``. The .in files take one canonical form, which every pip reads the same way
(``parse_in_file``): printable ASCII, one ``name==version`` pin per line with a canonical version and an optional
`` # comment``, and in requirements-dev.in one ``-r requirements.in``; anything else stops the script before pip runs.
A constrained version the resolution would move exits 1 and names it, and so does a pin whose chosen file PyPI does
not list; none of these writes anything. Last it prints the constraints' names the lock leaves out: with
--constraint, production's distributions no requirement reaches; without it, the dependencies the change dropped.
"""
import argparse
import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from packaging.version import Version

REPO = Path(__file__).resolve().parents[1]
RUNTIME_IN, RUNTIME_LOCK = "requirements.in", "requirements.txt"
DEV_IN, DEV_LOCK = "requirements-dev.in", "requirements-dev.txt"
HEADER = "# generated by ops/lock_requirements.py from {}; edit the .in file and run make lock\n"
PYPI_RELEASE = "https://pypi.org/pypi/{name}/{version}/json"
# A pin: its name, optional extras (name[extra]==1.0 pins name), then its version, with the whitespace PEP 508 allows
# around the extras and the == (name [extra] == 1.0). A version begins with a letter or digit, so a line whose version
# is missing is no pin, whatever follows it.
PIN = re.compile(r"([A-Za-z0-9][A-Za-z0-9._-]*)\s*(?:\[[^\]]*\])?\s*==\s*([A-Za-z0-9][^\s;#\\]*)")
# The .in files' one form (D-6), which every pip reads the same way. Whole file: only tab, LF, CR and printable ASCII;
# no "\" (pip joins the next line) and no "$" (pip expands ${VAR}); no coding declaration, pip's own pattern found
# anywhere in the first two lines as pip splits them, at LF only (pip/_internal/utils/encoding.py), since pip would
# decode the file by it. Each line, its trailing spaces and tabs ignored: blank, a comment, the include
# (requirements-dev.in only, exactly once) or a canonical pin, each with an optional trailing comment after a space or
# tab.
IN_BYTES = frozenset(b"\t\n\r" + bytes(range(0x20, 0x7F)))
IN_CODING = re.compile(rb"coding[:=]\s*([-\w.]+)")
IN_COMMENT = re.compile(r"[ \t]*#.*")
IN_INCLUDE = re.compile(r"-r[ \t]+requirements\.in(?:[ \t]+#.*)?")
IN_PIN = re.compile(r"([A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)"
                    r"==((?:[0-9]+!)?[0-9]+(?:\.[0-9]+)*(?:(?:a|b|rc)[0-9]+)?(?:\.post[0-9]+)?(?:\.dev[0-9]+)?)"
                    r"(?:[ \t]+#.*)?")
# pip's conflict report names each constraint it could not keep, at INFO level (pip 24.0,
# pip/_internal/resolution/resolvelib/factory.py), so pip runs without --quiet.
CONSTRAINT_LINE = re.compile(r"The user requested \(constraint\) ([A-Za-z0-9][A-Za-z0-9._-]*)(\S+)")
MOVE_HINT = "change that pin in requirements.in (or requirements-dev.in) to move it"
PIP_TAIL_LINES = 30
PIP_TIMEOUT_SEC = 1800

# {canonical name: (version, sha256 of the file pip chose)}
Resolved = Dict[str, Tuple[str, str]]


class Refused(Exception):
    """The lock is not written; the message says why."""


def canonical(name: str) -> str:
    """A distribution's name in its PEP 503 form."""
    return re.sub(r"[-_.]+", "-", name).lower()


def pins(path: Path) -> Dict[str, str]:
    """``{canonical name: version}`` of a lock, constraints or freeze file's ``name==version`` lines; its ``-r``,
    ``--hash`` and comment lines are skipped. The .in files are read by ``parse_in_file``."""
    found = {}
    for line in path.read_text().splitlines():
        match = PIN.match(line.strip())
        if match:
            found[canonical(match.group(1))] = match.group(2)
    return found


def _line_at(data: bytes, offset: int) -> int:
    """The number of the line holding byte ``offset``, counting LF, CR and CRLF as line ends."""
    return len(re.split(rb"\r\n|\r|\n", data[:offset]))


def _canonical_version(version: str) -> bool:
    """Whether ``version`` is its own normalised form. One ``Version`` cannot read is not: a release part longer than
    Python's integer-digit limit raises ``ValueError``."""
    try:
        return str(Version(version)) == version
    except ValueError:
        return False


def parse_in_file(path: Path) -> Dict[str, str]:
    """``{canonical name: version}`` of the .in file ``path``, which must take the one canonical form (``IN_*`` above):
    first the whole-file rules on its bytes, then each line, then no name pinned twice in it, nor, for
    requirements-dev.in, in requirements.in too. Anything else raises ``Refused``: ``<file>:<line>: not a canonical
    pin (name==version): <line>`` for a line, ``<file>: <rule>`` for a rule of the whole file."""
    data, name = path.read_bytes(), path.name
    odd = next((offset for offset, byte in enumerate(data) if byte not in IN_BYTES), None)
    if odd is not None:
        raise Refused(f"{name}: only tab, LF, CR and printable ASCII may appear (line {_line_at(data, odd)} holds "
                      f"byte 0x{data[odd]:02x})")
    odd = next((offset for offset, byte in enumerate(data) if byte in b"\\$"), None)
    if odd is not None:
        raise Refused(f"{name}: no \\ or $ may appear, which pip reads as a line continuation or a variable (line "
                      f"{_line_at(data, odd)})")
    for number, line in enumerate(data.split(b"\n")[:2], start=1):
        if IN_CODING.search(line):
            raise Refused(f"{name}: no coding declaration may appear in the first two lines, since pip would decode "
                          f"the file by it (line {number})")
    found: Dict[str, Tuple[str, int]] = {}
    includes = []
    for number, line in enumerate(data.decode("ascii").splitlines(), start=1):
        text = line.rstrip(" \t")
        if not text or IN_COMMENT.fullmatch(text):
            continue
        if name == DEV_IN and IN_INCLUDE.fullmatch(text):
            includes.append(number)
            continue
        match = IN_PIN.fullmatch(text)
        if not match or not _canonical_version(match.group(2)):
            raise Refused(f"{name}:{number}: not a canonical pin (name==version): {line}")
        pinned = canonical(match.group(1))
        if pinned in found:
            raise Refused(f"{name}: {pinned} is pinned twice (lines {found[pinned][1]} and {number})")
        found[pinned] = (match.group(2), number)
    if name == DEV_IN:
        if len(includes) != 1:
            raise Refused(f"{name}: needs exactly one -r requirements.in line, and has {len(includes)}")
        both = sorted(set(found) & set(parse_in_file(path.with_name(RUNTIME_IN))))
        if both:
            raise Refused(f"{name}: {', '.join(both)} pinned in {RUNTIME_IN} too")
    return {pinned: version for pinned, (version, _) in found.items()}


def run_pip(args: List[str]) -> Tuple[int, str]:
    """This interpreter's pip, run from the repo root: its exit code and its output, stdout and stderr together."""
    done = subprocess.run([sys.executable, "-m", "pip", *args], cwd=REPO, stdout=subprocess.PIPE,
                          stderr=subprocess.STDOUT, text=True, timeout=PIP_TIMEOUT_SEC)
    return done.returncode, done.stdout


def fetch_json(url: str) -> dict:
    with urllib.request.urlopen(url, timeout=60) as answer:
        return json.load(answer)


def constraints(constraint: Optional[Path], wanted: Dict[str, str]) -> Dict[str, str]:
    """The constraint set: ``constraint``'s pins when given; otherwise the committed lock's, less each name whose pin
    in a .in file (``wanted``) names another version, which is that pin's explicit move."""
    if constraint is not None:
        return pins(constraint)
    locked = {**pins(REPO / RUNTIME_LOCK), **pins(REPO / DEV_LOCK)}
    return {name: version for name, version in locked.items() if wanted.get(name, version) == version}


def write_pins(path: Path, held: Dict[str, str]) -> Path:
    path.write_text("".join(f"{name}=={version}\n" for name, version in sorted(held.items())))
    return path


def refuse_moves(moved: List[str], pip_tail: str = "") -> Refused:
    return Refused("\n".join([f"would move: {', '.join(moved)}", MOVE_HINT, *([pip_tail] if pip_tail else [])]))


def resolve(source: str, constraint_files: List[Path], held: Dict[str, str], report: Path) -> Resolved:
    """pip's resolution of the .in file ``source`` under ``constraint_files``, whose pins are ``held``. A failure
    names the constraints pip could not keep, from its conflict report; a result that holds a constrained name at
    another version is refused the same way."""
    args = ["install", "--dry-run", "--ignore-installed", "--disable-pip-version-check", "--report", str(report),
            "-r", source]
    for path in constraint_files:
        args += ["-c", str(path)]
    code, output = run_pip(args)
    if code != 0:
        tail = "\n".join(output.splitlines()[-PIP_TAIL_LINES:])
        named = list(dict.fromkeys(name + spec for name, spec in CONSTRAINT_LINE.findall(output)))
        raise refuse_moves(named, tail) if named else Refused(tail)
    resolved = {}
    for item in json.loads(report.read_text())["install"]:
        resolved[canonical(item["metadata"]["name"])] = (item["metadata"]["version"],
                                                        item["download_info"]["archive_info"]["hashes"]["sha256"])
    moved = [f"{name}=={held[name]}" for name, (version, _) in sorted(resolved.items())
             if name in held and version != held[name]]
    if moved:
        raise refuse_moves(moved)
    return resolved


def release_hashes(name: str, version: str, chosen: str) -> List[str]:
    """The sha256 of every file of the release on PyPI, which must list the file pip chose."""
    release = fetch_json(PYPI_RELEASE.format(name=name, version=version))
    hashes = sorted({file["digests"]["sha256"] for file in release["urls"]})
    if chosen not in hashes:
        raise Refused(f"PyPI lists no file of {name}=={version} with the sha256 pip chose ({chosen})")
    return hashes


def lock_text(source: str, entries: Dict[str, Tuple[str, List[str]]], include: str = "") -> str:
    """A lock file: the header, ``include`` (a ``-r`` line), then each pin, sorted, with its hashes."""
    lines = [HEADER.format(source), include]
    for name, (version, hashes) in sorted(entries.items()):
        lines.append(f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{sha}" for sha in hashes) + "\n")
    return "".join(lines)


def lock(constraint: Optional[Path]) -> Tuple[Dict[str, str], Resolved, Resolved]:
    """The constraint set and the two resolutions: the runtime set R, then the full set F, constrained by R too. Both
    .in files are read first, so a file outside their one form stops the lock before pip runs."""
    wanted = {**parse_in_file(REPO / RUNTIME_IN), **parse_in_file(REPO / DEV_IN)}
    held = constraints(constraint, wanted)
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        held_file = write_pins(work / "constraints.txt", held)
        runtime = resolve(RUNTIME_IN, [held_file], held, work / "runtime.json")
        runtime_pins = {name: version for name, (version, _) in runtime.items()}
        runtime_file = write_pins(work / "runtime.txt", runtime_pins)
        full = resolve(DEV_IN, [held_file, runtime_file], {**held, **runtime_pins}, work / "dev.json")
    differ = [f"{name}=={version}" for name, version in sorted(runtime_pins.items())
              if full.get(name, ("",))[0] != version]
    if differ:
        raise Refused(f"the dev resolution does not hold the runtime pins {', '.join(differ)}")
    return held, runtime, full


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Lock requirements.in and requirements-dev.in with hashes.")
    parser.add_argument("--constraint", type=Path, metavar="FILE",
                        help="constrain to FILE's name==version lines (the first lock, against production's pip "
                             "freeze) instead of the committed lock's pins")
    args = parser.parse_args(argv)
    try:
        held, runtime, full = lock(args.constraint)
        entries = {name: (version, release_hashes(name, version, chosen)) for name, (version, chosen) in full.items()}
    except Refused as exc:
        print(exc)
        return 1
    dev = {name: entry for name, entry in entries.items() if name not in runtime}
    (REPO / RUNTIME_LOCK).write_text(lock_text(RUNTIME_IN, {name: entries[name] for name in runtime}))
    (REPO / DEV_LOCK).write_text(lock_text(DEV_IN, dev, f"-r {RUNTIME_LOCK}\n"))
    kept = sum(1 for name in held if name in full)
    print(f"wrote {RUNTIME_LOCK} ({len(runtime)} pins) and {DEV_LOCK} ({len(dev)} more)")
    print(f"moved pins: none ({kept} of the {len(held)} constraints are in the lock, each at its version)")
    print(f"outside the lock: {', '.join(sorted(name for name in held if name not in full)) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
